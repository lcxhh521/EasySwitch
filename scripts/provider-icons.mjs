function escapeXml(value) {
  return value.replace(/[&<>"']/g, character => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" })[character]);
}

/** A reproducible hue from the displayed service name, independent of its alias. */
export function avatarHue(label) {
  return [...label].reduce((hue, character) => (hue * 31 + character.codePointAt(0)) % 360, 7);
}

/** Plain filenames stay mask-safe even before the UI fetches the manifest. */
export function letterAvatar(label, initials, colored = false) {
  if (!label.trim() || !/^[A-Z0-9]{1,2}$/.test(initials)) throw new Error("An avatar needs a service label and one or two initials");
  const hue = avatarHue(label);
  const fill = colored ? `hsl(${hue},45%,29%)` : "currentColor";
  const tile = colored ? `  <rect width="24" height="24" rx="6" fill="hsl(${hue},55%,91%)"/>\n` : "";
  return `<!-- Original EasySwitch letter avatar; generated by scripts/provider-icons.mjs. -->\n`
    + `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" role="img">\n`
    + `  <title>${escapeXml(label)} letter avatar</title>\n`
    + tile
    + `  <text x="12" y="16.5" text-anchor="middle" font-family="system-ui, sans-serif" font-size="${initials.length === 1 ? 17 : 12}" font-weight="700" fill="${fill}">${initials}</text>\n`
    + `</svg>\n`;
}

/** Pure generation: all output comes from the explicit catalog, never old SVGs. */
export function generateProviderIcons() {
  return Object.fromEntries(Object.entries(providerAvatars)
    .map(([name, [label, initials]]) => [`${name}.svg`, letterAvatar(label, initials, name.endsWith("-color"))]));
}

// Importing the generator does not inspect or modify any directory.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const directory = fileURLToPath(new URL("../web/icons/", import.meta.url));
  const icons = generateProviderIcons();
  for (const [name, svg] of Object.entries(icons)) writeFileSync(join(directory, name), svg);
  const manifest = writeIconManifest(directory);
  console.log(`${Object.keys(icons).length} original letter avatars; ${manifest.mono.length} monochrome`);
}
