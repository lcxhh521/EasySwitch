// Builds core/src/pricing/prices.json from opencodex's model metadata source
// (MIT, scripts/model-metadata.source.json): a compact table of USD prices per
// million tokens and a host -> vendor index, so a provider can be priced from
// its address. Run: node scripts/build-prices.mjs <path to model-metadata.source.json>
import { readFileSync, writeFileSync } from "node:fs";

const source = process.argv[2] ?? `${process.env.HOME}/workspace/opencodex/scripts/model-metadata.source.json`;
const data = JSON.parse(readFileSync(source, "utf8"));

// Subscription or login-based surfaces: their "price" is notional, not what the user pays per call.
const SKIP = new Set(["cursor", "github-copilot", "kiro", "google-antigravity", "google-gemini-cli", "openai-codex", "qwen-portal", "gitlab-duo", "kimi-code", "alibaba-coding-plan", "minimax-code", "minimax-code-cn", "opencode-go", "firepass", "amazon-bedrock", "azure-openai", "google-vertex", "cloudflare-ai-gateway"]);

const prices = {};
const hosts = {};
let count = 0;
for (const [vendor, models] of Object.entries(data)) {
  if (SKIP.has(vendor)) continue;
  for (const [id, m] of Object.entries(models)) {
    const c = m.cost;
    if (!c || !(c.input > 0 || c.output > 0)) continue;
    (prices[vendor] ??= {})[id] = [c.input ?? 0, c.output ?? 0, c.cacheRead ?? 0, c.cacheWrite ?? 0];
    count += 1;
    try {
      const host = new URL(m.baseUrl).hostname.toLowerCase();
      (hosts[host] ??= new Set()).add(vendor);
    } catch { /* no usable address */ }
  }
}
// A host maps to a vendor only when it is unambiguous.
const hostVendor = Object.fromEntries(Object.entries(hosts).filter(([, v]) => v.size === 1).map(([h, v]) => [h, [...v][0]]));
const out = { _about: "USD per 1M tokens: [input, output, cacheRead, cacheWrite]. Generated by scripts/build-prices.mjs from opencodex (MIT) model-metadata.source.json.", hostVendor, prices };
writeFileSync(new URL("../core/src/pricing/prices.json", import.meta.url), `${JSON.stringify(out)}\n`);
console.log(`${count} priced models, ${Object.keys(prices).length} vendors, ${Object.keys(hostVendor).length} hosts`);
